"""Build ``icons.js``: a small SVG sprite of PulsoIcon (https://pulsoicon.com) icons.

PulsoIcon ships only framework packages (React / Vue / Svelte) and has no CDN
build, so this script downloads the framework-free ``pulsoicon-core`` package
from the npm registry, reads the resting-frame shapes of the icons listed in
``ICON_NAMES`` and writes them as ``<symbol>`` elements into ``icons.js``.

The pages reference an icon with ``<svg class="pi"><use href="#pi-NAME"/></svg>``
(or ``icon('NAME')`` from JavaScript); stroke styling comes from ``.pi`` in
``style.css``. Only the static frame is used, the hover animations are not.

Usage::

    python scripts/build_icons.py

Complexity: O(k * s) time and space, where k is the number of icons and s the
size of one icon source file.
"""

from __future__ import annotations

import io
import json
import re
import tarfile
import urllib.request
from pathlib import Path

PACKAGE_VERSION: str = "6.1.0"
TARBALL_URL: str = (
    "https://registry.npmjs.org/pulsoicon-core/-/"
    f"pulsoicon-core-{PACKAGE_VERSION}.tgz"
)
OUTPUT_PATH: Path = Path(__file__).resolve().parent.parent / "icons.js"

# Icons used by index.html / planner.html / history.html and their scripts.
ICON_NAMES: tuple[str, ...] = (
    "arrow-left",
    "arrow-left-right",
    "arrow-right",
    "arrow-up",
    "chart-line",
    "chevron-down",
    "chevron-up",
    "fast-forward",
    "house",
    "layout-grid",
    "list",
    "map",
    "menu",
    "network",
    "pause",
    "play",
    "repeat",
    "rotate-ccw",
    "route",
    "rows-4",
    "search",
    "sliders-horizontal",
    "train-front",
    "x",
)

# One shape inside ``nodes: [...]``: ["tag", { key: "value", ... }, ...].
SHAPE_RE: re.Pattern[str] = re.compile(r'\[\s*"(\w+)",\s*\{([^{}]*)\}')
ATTR_RE: re.Pattern[str] = re.compile(r'(\w+):\s*"([^"]*)"')


def download_icon_sources(names: tuple[str, ...]) -> dict[str, str]:
    """Download the pinned package and return the JS source of each icon.

    Args:
        names: Kebab-case icon names (file names under ``dist/icons``).

    Returns:
        Mapping from icon name to the contents of ``dist/icons/<name>.js``.

    Raises:
        KeyError: If an icon does not exist in the package.
    """
    with urllib.request.urlopen(TARBALL_URL) as response:
        payload: bytes = response.read()

    sources: dict[str, str] = {}
    with tarfile.open(fileobj=io.BytesIO(payload), mode="r:gz") as archive:
        for name in names:
            member = archive.getmember(f"package/dist/icons/{name}.js")
            handle = archive.extractfile(member)
            if handle is None:
                raise KeyError(name)
            sources[name] = handle.read().decode("utf-8")
    return sources


def to_kebab(attr: str) -> str:
    """Convert a React-style attribute name (``strokeWidth``) to markup form."""
    return re.sub(r"[A-Z]", lambda m: "-" + m.group(0).lower(), attr)


def icon_markup(source: str) -> str:
    """Return the outline (non-solid) shapes of one icon as SVG markup.

    Only the ``nodes`` array is read; the ``solid`` variant that follows it is
    ignored. Motion metadata (the third tuple element) is dropped.

    Args:
        source: Contents of a ``dist/icons/<name>.js`` file.

    Returns:
        Concatenated SVG child elements, e.g. ``<path d="..."/>``.

    Raises:
        ValueError: If no shapes are found.
    """
    start = source.index("nodes:")
    end = source.find("solid:", start)
    block = source[start:] if end == -1 else source[start:end]

    parts: list[str] = []
    for tag, attr_text in SHAPE_RE.findall(block):
        # A static ``transform`` attribute is kept as is: without motion it
        # renders exactly like the wrapping <g> the package would create.
        attrs = " ".join(
            f'{to_kebab(key)}="{value}"'
            for key, value in ATTR_RE.findall(attr_text)
        )
        parts.append(f"<{tag} {attrs}/>")
    if not parts:
        raise ValueError("icon has no outline shapes")
    return "".join(parts)


def build_script(symbols: dict[str, str]) -> str:
    """Render ``icons.js`` from ``{name: inner SVG markup}``."""
    sprite = "".join(
        f'<symbol id="pi-{name}" viewBox="0 0 24 24">{markup}</symbol>'
        for name, markup in symbols.items()
    )
    return f"""\
// Generated by scripts/build_icons.py from pulsoicon-core@{PACKAGE_VERSION}
// (https://pulsoicon.com, ISC License). Do not edit by hand.
// Load this as the first element of <body>; it injects an SVG sprite and
// defines window.icon(name, extraClass) for markup built in JavaScript.
(function () {{
    var SPRITE = {json.dumps(sprite)};
    var holder = document.createElement('div');
    holder.innerHTML = '<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" ' +
        'style="position:absolute;width:0;height:0;overflow:hidden">' + SPRITE + '</svg>';
    document.body.insertBefore(holder.firstChild, document.body.firstChild);

    window.icon = function (name, extraClass) {{
        var cls = 'pi pi-' + name + (extraClass ? ' ' + extraClass : '');
        return '<svg class="' + cls + '" aria-hidden="true"><use href="#pi-' + name + '"/></svg>';
    }};
}})();
"""


def main() -> None:
    """Download the icons and write ``icons.js``."""
    sources = download_icon_sources(ICON_NAMES)
    symbols = {name: icon_markup(sources[name]) for name in ICON_NAMES}
    OUTPUT_PATH.write_text(build_script(symbols), encoding="utf-8")
    print(f"Wrote {len(symbols)} icons to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
